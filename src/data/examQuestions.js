// Robust and crash-proof Adaptive Quiz Generator
export function generateAdaptiveQuiz(userVocabulary) {
  const defaultFallbackPool = [
    { word: "persevere", meaningTr: "azimle devam etmek, yılmamak", ipa: "/ˌpɜː.sɪˈvɪər/", exampleEn: "Despite difficulties, they persevered with the research.", level: "C1" },
    { word: "unravel", meaningTr: "çözmek, aydınlatmak", ipa: "/ʌnˈræv.əl/", exampleEn: "Scientists are trying to unravel the mysteries.", level: "B2" },
    { word: "substantiate", meaningTr: "kanıtlamak, somut delille desteklemek", ipa: "/səbˈstæn.ʃi.eɪt/", exampleEn: "More data is needed to substantiate the claim.", level: "C1" },
    { word: "exacerbate", meaningTr: "kötüleştirmek, alevlendirmek", ipa: "/ɪɡˈzæs.ə.beɪt/", exampleEn: "The storm exacerbated the severe flooding.", level: "B2" },
    { word: "mitigate", meaningTr: "hafifletmek, etkisini azaltmak", ipa: "/ˈmɪt.ɪ.ɡeɪt/", exampleEn: "We must adopt policies to mitigate climate change.", level: "C1" }
  ];

  // Merge user vocabulary with fallback pool
  const candidatePool = (userVocabulary && Array.isArray(userVocabulary) && userVocabulary.length > 0)
    ? userVocabulary.filter(w => w && w.word && typeof w.word === 'string' && w.word.trim().length > 0)
    : defaultFallbackPool;

  const validPool = candidatePool.length > 0 ? candidatePool : defaultFallbackPool;
  const shuffled = [...validPool].sort(() => 0.5 - Math.random());
  const selectedWords = shuffled.slice(0, Math.min(5, shuffled.length));

  const standardDistractors = ["mitigate", "exacerbate", "persevere", "substantiate", "ubiquitous", "indispensable", "facilitate", "encourage"];

  return selectedWords.map((wordItem, idx) => {
    const wordText = wordItem.word.trim();
    const meaningText = wordItem.meaningTr || "Türkçe anlamı";
    const exampleText = (wordItem.exampleEn && typeof wordItem.exampleEn === 'string' && wordItem.exampleEn.includes(' '))
      ? wordItem.exampleEn
      : `The expert highlighted that it is essential to ${wordText} the findings.`;

    // Generate distractors
    const otherWords = validPool.filter(w => w.word.toLowerCase() !== wordText.toLowerCase()).map(w => w.word);
    const pool = otherWords.length >= 3 ? otherWords : standardDistractors.filter(d => d.toLowerCase() !== wordText.toLowerCase());
    const distractors = [...pool].sort(() => 0.5 - Math.random()).slice(0, 3);

    // Combine correct answer and distractors (4 options: A, B, C, D)
    const optionsArray = [wordText, ...distractors].sort(() => 0.5 - Math.random());
    const correctIndex = optionsArray.indexOf(wordText);
    const letterKeys = ["A", "B", "C", "D"];
    const correctLetter = letterKeys[correctIndex >= 0 ? correctIndex : 0];

    // Cloze question
    let questionText = "";
    const wordRegex = new RegExp(`\\b${wordText}\\b`, 'gi');
    if (wordRegex.test(exampleText)) {
      questionText = exampleText.replace(wordRegex, "----");
    } else {
      questionText = `Aşağıdaki boşluğa veya anlama en uygun kelimeyi seçiniz: '${meaningText}'`;
    }

    return {
      id: `adaptive-${wordItem.id || idx}-${Date.now()}-${idx}`,
      examType: "Adaptive Memory Quiz",
      category: `Hafıza Havuzun: ${wordText} (${wordItem.level || 'B2'})`,
      difficulty: "Kişiselleştirilmiş Akıllı Soru",
      question: questionText,
      options: optionsArray.map((opt, i) => ({
        key: letterKeys[i] || `${i + 1}`,
        text: opt
      })),
      correctAnswer: correctLetter,
      explanation: `'${wordText}' (${wordItem.ipa || ''}) ifadesi '${meaningText}' anlamına gelmektedir.`,
      strategyTip: `Bu kelime hafıza havuzunuzda kayıtlıdır (Tekrar Aralığı: ${wordItem.interval || 1} gün).`
    };
  });
}
